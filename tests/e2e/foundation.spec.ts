import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
const username = "household";
const password = "e2e-only-password-12345";
const secret = "e2e-fixture-only-secret-not-for-live-use-123456";

test("initial setup, authentication, protected mock devices and logout work accessibly", async ({ page }, info) => {
  await page.goto("/");
  await expect(page).toHaveURL(/\/setup$/);
  await expect(page.getByRole("heading", { name: "Make yourself at home." })).toBeVisible();
  expect((await page.request.get("/api/devices")).status()).toBe(401);
  expect(await page.content()).not.toContain(secret);
  const blocked = await page.request.post("/api/auth/setup", { headers: { Origin: "https://attacker.example" }, data: { username, password, secret } });
  expect(blocked.status()).toBe(403);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: info.outputPath("setup.png"), fullPage: true });
  await page.getByLabel("Server setup secret").fill(secret);
  await page.getByLabel("Username", { exact: true }).fill(username);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Create administrator" }).click();
  await expect(page).toHaveURL(/\/login\?created=1$/);
  await expect(page.getByRole("status")).toContainText("account is ready");
  await page.getByLabel("Username", { exact: true }).fill(username);
  await page.getByLabel("Password", { exact: true }).fill("wrong-password");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByText("Username or password is incorrect.", { exact: true })).toBeVisible();
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your household", exact: true })).toBeVisible();
  await expect(page.getByText("Living room speaker", { exact: true })).toBeVisible();
  await expect(page.getByText(/· Mock device$/)).toHaveCount(3);
  await expect(page.getByText("Not tested", { exact: true })).toHaveCount(3);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"]).analyze()).violations).toEqual([]);
  const api = await page.request.get("/api/devices"); expect(api.status()).toBe(200); expect((await api.json()).devices).toHaveLength(3);
  const cookie = (await page.context().cookies()).find(item => item.name === "hnh_session")!;
  expect(cookie.httpOnly).toBe(true); expect(cookie.sameSite).toBe("Strict");
  await page.screenshot({ path: info.outputPath("dashboard.png"), fullPage: true });
  await page.reload(); await expect(page.getByRole("heading", { name: "Your household", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  expect((await page.request.get("/api/devices")).status()).toBe(401);
  await page.goto("/"); await expect(page).toHaveURL(/\/login$/);
  await page.goto("/setup"); await expect(page).toHaveURL(/\/login$/);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"]).analyze()).violations).toEqual([]);
});
